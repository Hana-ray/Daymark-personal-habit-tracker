CREATE TABLE IF NOT EXISTS accounts (
  email VARCHAR(150) PRIMARY KEY,
  password_hash VARCHAR(100) NOT NULL,
  zone VARCHAR(80) NOT NULL
);
CREATE TABLE IF NOT EXISTS habits (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner VARCHAR(150) NOT NULL REFERENCES accounts(email),
  name VARCHAR(80) NOT NULL,
  schedule INTEGER NOT NULL CHECK (schedule BETWEEN 1 AND 127),
  created DATE NOT NULL,
  archived DATE
);
CREATE INDEX IF NOT EXISTS habits_owner ON habits(owner);
CREATE TABLE IF NOT EXISTS checkins (
  habit_id BIGINT NOT NULL REFERENCES habits(id),
  check_date DATE NOT NULL,
  PRIMARY KEY (habit_id, check_date)
);

CREATE TABLE IF NOT EXISTS habit_schedules (
  habit_id BIGINT NOT NULL REFERENCES habits(id),
  effective_on DATE NOT NULL,
  schedule INTEGER NOT NULL CHECK (schedule BETWEEN 1 AND 127),
  PRIMARY KEY (habit_id, effective_on)
);

ALTER TABLE habits ADD COLUMN IF NOT EXISTS category VARCHAR(40) NOT NULL DEFAULT 'Uncategorized';
